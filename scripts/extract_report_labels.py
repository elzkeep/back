#!/usr/bin/env python3
"""앱(../app/lib/screens/data/dataitem/*.dart)의 점검 항목 정의에서 선택형(select) 항목의 선택지를 뽑아
controllers/api/reportlabels.go 를 만든다. 점검 결과(item_tb)에는 선택지 '번호'만 저장되므로
보고서 PDF 가 번호를 글자로 바꾸려면 이 표가 필요하다.

  python3 scripts/extract_report_labels.py ../app/lib/screens/data/dataitem > controllers/api/reportlabels.go
"""
import os
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else '../app/lib/screens/data/dataitem'

data_re = re.compile(r"Data\(\s*(?:[^()]*?)title:\s*'([^']*)'", re.S)
item_re = re.compile(r"Item\(\s*type:\s*ItemType\.select,\s*title:\s*'([^']*)',\s*extra:\s*\{\s*'select':\s*\[(.*?)\]", re.S)
option_re = re.compile(r"CItem\(\s*id:\s*(\d+),\s*value:\s*'([^']*)'\s*\)")

labels = {}  # (data title, item title) -> {id: label}
for name in sorted(os.listdir(src)):
    if not name.endswith('.dart'):
        continue
    text = open(os.path.join(src, name), encoding='utf-8').read()
    # Data(...) 제목 위치를 기준으로 그 뒤에 나오는 선택형 항목을 묶는다
    marks = [(m.start(), m.group(1)) for m in data_re.finditer(text)]
    for m in item_re.finditer(text):
        data_title = ''
        for pos, title in marks:
            if pos < m.start():
                data_title = title
            else:
                break
        options = {int(i): v for i, v in option_re.findall(m.group(2))}
        if options:
            labels.setdefault((data_title, m.group(1)), options)

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

print('// Code generated by scripts/extract_report_labels.py; DO NOT EDIT.')
print('// 앱 점검 항목 정의(app/lib/screens/data/dataitem)의 선택형 항목 선택지. 키 = "점검구분 제목|항목 제목"')
print()
print('package api')
print()
print('var reportSelectLabels = map[string]map[int]string{')
for (data_title, item_title), options in sorted(labels.items()):
    body = ', '.join(f'{k}: {q(v)}' for k, v in sorted(options.items()))
    print(f'\t{q(data_title + "|" + item_title)}: {{{body}}},')
print('}')
